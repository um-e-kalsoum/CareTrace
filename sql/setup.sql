-- CareTrace reconstruction script. WARNING: CREATE OR REPLACE resets existing tables/notes.
-- If CoCo already created and populated CARETRACE, DO NOT rerun this script.
CREATE DATABASE IF NOT EXISTS CARETRACE;

CREATE OR REPLACE TABLE CARETRACE.PUBLIC.DEMO_TIMELINE (
    PATIENT_ID        NUMBER(38,0),
    EVENT_DATE        TIMESTAMP_NTZ,
    EVENT_TYPE        VARCHAR,
    EVENT_DESCRIPTION VARCHAR,
    SOURCE_RECORD_ID  NUMBER(38,0)
) AS
WITH timeline AS (
    SELECT PATIENT_ID, CONDITION_START::TIMESTAMP_NTZ AS EVENT_DATE,
           'CONDITION' AS EVENT_TYPE, DESCRIPTION AS EVENT_DESCRIPTION,
           CONDITION_ID AS SOURCE_RECORD_ID
    FROM SYNTHETIC_HEALTHCARE_DATA_CLINICAL_AND_CLAIMS.SILVER.CONDITIONS
    WHERE PATIENT_ID = 1563304
      AND DESCRIPTION ILIKE ANY ('%pregnancy%','%miscarriage%','%eclampsia%',
          '%tubal%','%blighted ovum%','%hypertension%','%anemia%','%obesity%')
    UNION ALL
    SELECT PATIENT_ID, ENCOUNTER_START, 'ENCOUNTER ('||ENCOUNTERCLASS||')',
           DESCRIPTION, ENCOUNTER_ID
    FROM SYNTHETIC_HEALTHCARE_DATA_CLINICAL_AND_CLAIMS.SILVER.ENCOUNTERS
    WHERE PATIENT_ID = 1563304
      AND DESCRIPTION ILIKE ANY ('%prenatal%','%birth%','%pregnan%','%emergency%')
    UNION ALL
    SELECT PATIENT_ID, OBSERVATION_DATE, 'OBSERVATION ('||CATEGORY||')',
           DESCRIPTION||' = '||VALUE||COALESCE(' '||UNITS,''), OBSERVATION_ID
    FROM SYNTHETIC_HEALTHCARE_DATA_CLINICAL_AND_CLAIMS.SILVER.OBSERVATIONS
    WHERE PATIENT_ID = 1563304 AND OBSERVATION_DATE >= '2019-08-01'
      AND DESCRIPTION ILIKE ANY ('%blood pressure%','%body weight%',
          '%hemoglobin%','%hcg%','%glucose%') AND VALUE IS NOT NULL
    QUALIFY ROW_NUMBER() OVER (PARTITION BY DATE_TRUNC('month',
          OBSERVATION_DATE), DESCRIPTION ORDER BY OBSERVATION_DATE) = 1
)
SELECT * FROM timeline ORDER BY EVENT_DATE LIMIT 15;

CREATE OR REPLACE TABLE CARETRACE.PUBLIC.USER_NOTES (
    NOTE_ID    NUMBER(38,0) AUTOINCREMENT START 1 INCREMENT 1,
    PATIENT_ID NUMBER(38,0) NOT NULL,
    NOTE_DATE  TIMESTAMP_NTZ NOT NULL,
    SYMPTOM    VARCHAR NOT NULL,
    SEVERITY   NUMBER(2,0) NOT NULL,
    NOTES      VARCHAR,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

SELECT COUNT(*) AS TIMELINE_ROWS FROM CARETRACE.PUBLIC.DEMO_TIMELINE;
